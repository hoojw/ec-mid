CREATE TABLE IF NOT EXISTS ec_dw.input_store_product_rule (
 `店铺编码` VARCHAR(32) NOT NULL, `69码` VARCHAR(32) NOT NULL,
 `商品分类` VARCHAR(16) NULL, `单盒运营底价` DECIMAL(18,4) NULL,
 `售卖时段` VARCHAR(16) NULL, `禁售区域` VARCHAR(255) NULL,
 `填写人` VARCHAR(64) NOT NULL, `更新时间` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (`店铺编码`,`69码`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='运营手工维护规则，不替代平台资质或法律合规判断';
CREATE TABLE IF NOT EXISTS ec_dw.ops_patrol_run (
 `批次ID` CHAR(36) PRIMARY KEY, `店铺编码` VARCHAR(32) NOT NULL,
 `检查数量` INT NOT NULL, `低价数量` INT NOT NULL, `待维护数量` INT NOT NULL,
 `价格通过数量` INT NOT NULL, `检查明细` JSON NOT NULL,
 `填写人` VARCHAR(64) NOT NULL, `创建时间` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (`店铺编码`,`创建时间`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='基于已采集售价和人工规则的价格巡检快照';
CREATE TABLE IF NOT EXISTS ec_dw.ops_followup (
 `模块` VARCHAR(16) NOT NULL, `对象键` VARCHAR(255) NOT NULL,
 `跟进状态` VARCHAR(16) NOT NULL, `备注` VARCHAR(500) NOT NULL,
 `填写人` VARCHAR(64) NOT NULL, `更新时间` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (`模块`,`对象键`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='中台内部跟进，不修改平台售后或订单状态';
CREATE TABLE IF NOT EXISTS ec_dw.ops_business_audit (
 `序号` BIGINT AUTO_INCREMENT PRIMARY KEY, `模块` VARCHAR(16) NOT NULL,
 `对象键` VARCHAR(255) NOT NULL, `变更前` JSON NOT NULL, `变更后` JSON NOT NULL,
 `填写人` VARCHAR(64) NOT NULL, `创建时间` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
